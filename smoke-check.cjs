"use strict";

/*
 * Lightweight repository smoke checks for the static SMITHX prototype.
 * This validates references and syntax; it does not replace browser QA,
 * backend security tests, or payment-provider verification.
 */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = __dirname;
const errors = [];
const htmlFiles = fs.readdirSync(root).filter((name) => name.endsWith(".html")).sort();

function localTarget(raw, sourceFile) {
  const value = String(raw || "").trim();
  if (!value || value.startsWith("#") || value.startsWith("//")) return null;
  // Ignore attribute templates generated by JavaScript at runtime.
  if (value.includes("${") || value.includes("{{")) return null;
  if (/^(?:[a-z][a-z0-9+.-]*:)/i.test(value)) return null;
  const pathname = decodeURIComponent(value.split(/[?#]/, 1)[0]);
  if (!pathname) return null;
  const absolute = path.resolve(path.dirname(path.join(root, sourceFile)), pathname);
  if (absolute !== root && !absolute.startsWith(root + path.sep)) {
    return { outsideRoot: absolute };
  }
  return { absolute };
}

for (const file of htmlFiles) {
  const source = fs.readFileSync(path.join(root, file), "utf8");
  const styleHrefs = new Set();

  for (const match of source.matchAll(/<link\b([^>]*)>/gi)) {
    const attrs = match[1];
    if (!/\brel\s*=\s*["']?stylesheet\b/i.test(attrs)) continue;
    const href = attrs.match(/\bhref\s*=\s*["']([^"']+)["']/i)?.[1];
    if (!href) {
      errors.push(file + ": stylesheet link has no quoted href");
      continue;
    }
    const normalized = href.split(/[?#]/, 1)[0];
    if (styleHrefs.has(normalized)) errors.push(file + ": duplicate stylesheet " + normalized);
    styleHrefs.add(normalized);
  }

  for (const match of source.matchAll(/\b(?:href|src)\s*=\s*["']([^"']*)["']/gi)) {
    const raw = match[1];
    const target = localTarget(raw, file);
    if (!target) continue;
    if (target.outsideRoot) {
      errors.push(file + ": local reference escapes repository root: " + raw);
    } else if (!fs.existsSync(target.absolute)) {
      errors.push(file + ": missing local file reference: " + raw);
    }
  }

  for (const match of source.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    const attrs = match[1];
    const body = match[2];
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = attrs.match(/\btype\s*=\s*["']([^"']+)["']/i)?.[1]?.toLowerCase();
    if (type && !["text/javascript", "application/javascript", "module"].includes(type)) continue;
    if (type === "module") continue; // Node's vm.Script parses classic scripts only.
    try {
      new vm.Script(body, { filename: file + " (inline script)" });
    } catch (error) {
      errors.push(file + ": inline JavaScript syntax error: " + error.message);
    }
  }
}

if (errors.length) {
  console.error("SMITHX smoke checks failed:");
  for (const error of errors) console.error(" - " + error);
  process.exitCode = 1;
} else {
  console.log("SMITHX smoke checks passed: " + htmlFiles.length + " HTML pages checked for local references, duplicate stylesheets, and inline script syntax.");
}
